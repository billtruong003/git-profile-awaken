// Copies the logos the widgets can show from simple-icons (CC0) into the source tree, so the Action does not
// install the whole icon library on every run. Run: npm run vendor:icons
import { writeFileSync } from 'node:fs';
import * as icons from 'simple-icons';

const get = (slug) => icons[`si${slug[0].toUpperCase()}${slug.slice(1)}`];

/** GitHub language name → simple-icons slug, for the skills widget. */
const LANGUAGES = {
  'C#': 'dotnet', TypeScript: 'typescript', JavaScript: 'javascript', Python: 'python', 'Jupyter Notebook': 'jupyter',
  HTML: 'html5', CSS: 'css', SCSS: 'sass', Sass: 'sass', C: 'c', 'C++': 'cplusplus', Rust: 'rust', Go: 'go',
  Kotlin: 'kotlin', Swift: 'swift', Dart: 'dart', PHP: 'php', Ruby: 'ruby', Lua: 'lua', Shell: 'gnubash',
  ShaderLab: 'unity', HLSL: 'unity', GDScript: 'godotengine', Haskell: 'haskell', Elixir: 'elixir', Scala: 'scala',
  R: 'r', Julia: 'julia', Vue: 'vuedotjs', Svelte: 'svelte', Zig: 'zig', Nim: 'nim', Clojure: 'clojure', Perl: 'perl',
  Solidity: 'solidity', GLSL: 'opengl', Markdown: 'markdown', Dockerfile: 'docker', Nix: 'nixos', HCL: 'terraform',
  OCaml: 'ocaml', 'F#': 'fsharp', Erlang: 'erlang', WebAssembly: 'webassembly', TeX: 'latex', MDX: 'mdx',
};

/** Social links (Guild Contacts). */
const SOCIAL = [
  'github', 'gitlab', 'youtube', 'facebook', 'instagram', 'x', 'discord', 'tiktok', 'twitch', 'medium', 'devdotto',
  'hashnode', 'stackoverflow', 'leetcode', 'kaggle', 'reddit', 'telegram', 'threads', 'bluesky', 'mastodon',
  'patreon', 'buymeacoffee', 'kofi', 'itchdotio', 'steam', 'behance', 'dribbble', 'substack', 'spotify', 'zalo',
  'messenger', 'whatsapp', 'line', 'bilibili', 'huggingface', 'npm', 'artstation', 'pinterest', 'producthunt',
  'hackerrank', 'codeforces', 'orcid', 'googlescholar',
];

import { TECH_CATEGORIES } from './tech-catalog.mjs';

const pick = (slugs) => Object.fromEntries([...new Set(slugs)].flatMap((slug) => {
  const icon = get(slug);
  return icon ? [[slug, { title: icon.title, path: icon.path }]] : [];
}));

const languages = Object.fromEntries(Object.entries(LANGUAGES).flatMap(([name, slug]) => (get(slug) ? [[name, get(slug).path]] : [])));
const social = pick(SOCIAL);
const tech = {};
for (const [category, slugs] of Object.entries(TECH_CATEGORIES)) {
  for (const slug of slugs) {
    const icon = get(slug);
    if (icon && !tech[slug]) tech[slug] = { title: icon.title, path: icon.path, category };
  }
}

writeFileSync(
  new URL('../src/presentation/svg/brandIcons.ts', import.meta.url),
  `// Generated by scripts/vendor-brand-icons.mjs from simple-icons (CC0-1.0). Logos are trademarks of their owners.
// All paths are on a 24x24 grid.

/** GitHub language name → path, for the skills widget. */
export const BRAND_ICONS: Record<string, string> = ${JSON.stringify(languages, null, 2)};

export interface BrandIcon {
  title: string;
  path: string;
}

/** Social networks, by simple-icons slug. */
export const SOCIAL_ICONS: Record<string, BrandIcon> = ${JSON.stringify(social, null, 2)};

/** Technologies for the Arsenal widget, by simple-icons slug, each with the catalog category it is listed under first. */
export const TECH_ICONS: Record<string, BrandIcon & { category: string }> = ${JSON.stringify(tech)};

export const TECH_CATEGORY_NAMES = ${JSON.stringify(Object.keys(TECH_CATEGORIES))} as const;
`,
);
console.log(`${Object.keys(languages).length} language, ${Object.keys(social).length} social and ${Object.keys(tech).length} tech icons written`);
